"""Настройки лабораторной работы № 3.

Все параметры алгоритмов собраны здесь, чтобы их было видно в одном месте:
размеры блоков и ключей, число раундов, таблицы замен ГОСТ и порядок байтов.
"""


class LabConfig:
    """Параметры трёх реализаций: ГОСТ 28147-89, AES-128 и RC4."""

    def __init__(self) -> None:
        # ---- ГОСТ 28147-89 ----
        self.gost_block_bytes = 8      # блок 64 бита
        self.gost_key_bytes = 32       # ключ 256 бит
        self.gost_rounds = 32          # 32 раунда сети Фейстеля
        self.gost_rotate = 11          # циклический сдвиг на 11 бит
        self.gost_byte_order = "little"  # как принято в ГОСТ 28147-89

        # Таблицы замен (S-боксы) id-tc26-gost-28147-param-Z.
        # Это тот самый набор, который в 2015 году зафиксировали в ГОСТ Р 34.12-2015
        # для алгоритма «Магма»: 8 таблиц по 16 значений, каждая на свой 4-битный кусок.
        self.gost_sbox = (
            (12, 4, 6, 2, 10, 5, 11, 9, 14, 8, 13, 7, 0, 3, 15, 1),
            (6, 8, 2, 3, 9, 10, 5, 12, 1, 14, 4, 7, 11, 13, 0, 15),
            (11, 3, 5, 8, 2, 15, 10, 13, 14, 1, 7, 4, 12, 9, 6, 0),
            (12, 8, 2, 1, 13, 4, 15, 6, 7, 0, 10, 5, 3, 14, 9, 11),
            (7, 15, 5, 10, 8, 1, 6, 13, 0, 9, 3, 14, 11, 4, 2, 12),
            (5, 13, 15, 6, 9, 2, 12, 10, 11, 7, 8, 1, 4, 3, 14, 0),
            (8, 14, 2, 5, 6, 9, 1, 12, 15, 4, 11, 0, 13, 10, 3, 7),
            (1, 7, 14, 13, 0, 5, 8, 3, 4, 15, 10, 6, 9, 12, 11, 2),
        )

        # ---- AES-128 ----
        self.aes_block_bytes = 16      # блок 128 бит
        self.aes_key_bytes = 16        # ключ 128 бит
        self.aes_rounds = 10           # 10 раундов + начальное сложение с ключом
        self.aes_state_side = 4        # матрица состояния 4 x 4 байта
        self.aes_word_bytes = 4        # слово AES — 4 байта

        # ---- RC4 ----
        self.rc4_state_size = 256      # массив S и все операции по модулю 256
        self.rc4_min_key_bytes = 1
        self.rc4_max_key_bytes = 256
        self.rc4_gamma_preview = 16    # сколько байтов гаммы печатать в демо


config = LabConfig()
